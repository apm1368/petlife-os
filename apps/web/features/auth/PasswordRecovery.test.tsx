import { beforeEach, expect, it, vi } from "vitest";
import { fireEvent, screen, waitFor } from "@testing-library/react";
import { renderWithIntl } from "@/test/render-with-intl";
import ForgotPasswordPage from "@/app/[locale]/(auth)/account/forgot/page";
import { authService } from "@/services/auth.service";
vi.mock("next/navigation", () => ({ useSearchParams: () => new URLSearchParams() }));
vi.mock("@/services/auth.service", () => ({ authService: { forgotPassword: vi.fn(), resetPassword: vi.fn() } }));
beforeEach(() => vi.resetAllMocks());
it("keeps recovery retryable after a transport failure", async () => {
 vi.mocked(authService.forgotPassword).mockRejectedValueOnce(new Error("offline")).mockResolvedValueOnce({ ok: true });
 renderWithIntl(<ForgotPasswordPage />);
 fireEvent.change(screen.getByRole("textbox"), {target:{value:"review_user"}});
 fireEvent.click(screen.getByRole("button", { name: "Text me a reset code" }));
 expect(await screen.findByRole("alert")).toBeTruthy();
 expect(screen.getByRole("textbox")).toBeTruthy();
 fireEvent.click(screen.getByRole("button", { name: "Text me a reset code" }));
 await screen.findByText(/If this username has a verified mobile/i);
 expect(screen.queryByRole("alert")).toBeNull();
});
it("resets the password with the texted code", async () => {
 vi.mocked(authService.forgotPassword).mockResolvedValue({ ok: true });
 vi.mocked(authService.resetPassword).mockResolvedValue({ ok: true });
 renderWithIntl(<ForgotPasswordPage />);
 fireEvent.change(screen.getByRole("textbox"), {target:{value:"review_user"}});
 fireEvent.click(screen.getByRole("button", { name: "Text me a reset code" }));
 await screen.findByText(/If this username has a verified mobile/i);
 fireEvent.paste(screen.getAllByRole("textbox")[0]!, { clipboardData: { getData: () => "654321" } });
 fireEvent.change(screen.getByLabelText("New password"), {target:{value:"brand-new-pass"}});
 fireEvent.change(screen.getByLabelText("Confirm password"), {target:{value:"brand-new-pass"}});
 fireEvent.click(screen.getByRole("button", { name: "Set new password" }));
 await waitFor(() => expect(authService.resetPassword).toHaveBeenCalledWith({ username: "review_user", code: "654321", newPassword: "brand-new-pass" }));
 expect(await screen.findByText("Your password has been reset. You can now log in.")).toBeTruthy();
});
