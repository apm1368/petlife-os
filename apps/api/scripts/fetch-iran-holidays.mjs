#!/usr/bin/env node
/**
 * Regenerates src/common/time/iran-holidays.data.ts — Iran's official public holidays — from holidayapi.ir.
 *
 *   node scripts/fetch-iran-holidays.mjs 1405 1406 [--provisional 1406]
 *
 * Run by a developer once a year (after the official calendar for the next Persian year is published) and commit the
 * result; the API never calls a third party at request time. Fridays are left out (business-hours.ts already closes
 * them); a holiday that falls on a Friday is kept. The API answers one day per request (~8 s), so a year takes a few
 * minutes at the polite concurrency below.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const provisional = new Set();
const years = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--provisional") provisional.add(Number(args[++i]));
  else years.push(Number(args[i]));
}
if (!years.length || years.some((y) => !Number.isInteger(y) || y < 1400 || y > 1500)) {
  console.error("usage: fetch-iran-holidays.mjs <persianYear>… [--provisional <persianYear>]");
  process.exit(2);
}

const persian = new Intl.DateTimeFormat("en-u-ca-persian-nu-latn", { year: "numeric", month: "numeric", day: "numeric", timeZone: "UTC" });
function jalaliOf(date) {
  const parts = Object.fromEntries(persian.formatToParts(date).filter((p) => p.type !== "literal").map((p) => [p.type, Number.parseInt(p.value, 10)]));
  return { y: parts.year, m: parts.month, d: parts.day };
}
/** Every Gregorian day of a Persian year, with its Jalali date. */
function daysOf(year) {
  const out = [];
  // 1 Farvardin is always 20–21 March of Gregorian year (year + 621).
  for (let t = Date.UTC(year + 621, 2, 15); ; t += 86400000) {
    const date = new Date(t);
    const j = jalaliOf(date);
    if (j.y < year) continue;
    if (j.y > year) break;
    out.push({ iso: date.toISOString().slice(0, 10), j });
  }
  return out;
}

const pad = (n) => String(n).padStart(2, "0");
async function fetchDay(j, attempt = 1) {
  const url = `https://holidayapi.ir/jalali/${j.y}/${pad(j.m)}/${pad(j.d)}`;
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(30_000), headers: { accept: "application/json" } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } catch (error) {
    if (attempt >= 4) throw new Error(`${url}: ${error.message}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
    return fetchDay(j, attempt + 1);
  }
}

const holidays = [];
for (const year of years) {
  const days = daysOf(year);
  let next = 0;
  let done = 0;
  async function worker() {
    while (next < days.length) {
      const day = days[next++];
      const body = await fetchDay(day.j);
      const events = (body.events ?? []).filter((e) => e.is_holiday && e.description.trim() !== "جمعه");
      if (events.length) {
        holidays.push({
          date: day.iso,
          jalali: `${day.j.y}-${pad(day.j.m)}-${pad(day.j.d)}`,
          title: events.map((e) => e.description.trim()).join(" · "),
          religious: events.some((e) => e.is_religious),
        });
      }
      if (++done % 30 === 0) console.error(`${year}: ${done}/${days.length}`);
    }
  }
  await Promise.all(Array.from({ length: 6 }, worker));
  console.error(`${year}: ${holidays.filter((h) => h.jalali.startsWith(String(year))).length} holidays`);
}
holidays.sort((a, b) => a.date.localeCompare(b.date));

const target = fileURLToPath(new URL("../src/common/time/iran-holidays.data.ts", import.meta.url));
const stamp = new Date().toISOString().slice(0, 10);
const yearsLine = years.map((y) => `  ${y}: "${provisional.has(y) ? "provisional" : "official"}",`).join("\n");
const rows = holidays.map((h) => `  { date: "${h.date}", jalali: "${h.jalali}", title: ${JSON.stringify(h.title)}, religious: ${h.religious} },`).join("\n");
writeFileSync(
  target,
  `// Generated by scripts/fetch-iran-holidays.mjs from holidayapi.ir on ${stamp} — do not edit by hand; staff add or\n` +
    `// override days in the admin (Settings → Holidays and closures), and a developer regenerates this once a year.\n` +
    `import type { OfficialHoliday } from "./iran-holidays";\n\n` +
    `/** Persian years covered here. "provisional": lunar holidays not yet confirmed by the official calendar. */\n` +
    `export const IRAN_HOLIDAY_YEARS: Readonly<Record<number, "official" | "provisional">> = {\n${yearsLine}\n};\n\n` +
    `export const IRAN_OFFICIAL_HOLIDAYS: readonly OfficialHoliday[] = [\n${rows}\n];\n`,
);
console.error(`wrote ${holidays.length} holidays to ${target}`);
